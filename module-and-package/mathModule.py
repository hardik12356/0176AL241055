import math

num = int(input("Enter a number: "))

print("Square Root:", math.sqrt(num))
print("Power:", math.pow(num, 2))
print("Factorial:", math.factorial(num))
print("Sine:", math.sin(math.radians(num)))
print("Cosine:", math.cos(math.radians(num)))
print("Tangent:", math.tan(math.radians(num)))